/// The moods the journal has always offered. `value` is what the API
/// stores; order and values are unchanged.
@immutable
class JournalMood {
  const JournalMood(this.value, this.emoji);

  final String value;
  final String emoji;

  String get label => 'journal_mood_$value'.tr();

  static const List<JournalMood> all = [
    JournalMood('peaceful', '🙏'),
    JournalMood('joyful', '😊'),
    JournalMood('enlightened', '✨'),
    JournalMood('reflective', '🤔'),
    JournalMood('emotional', '😢'),
  ];

  /// Known mood for a stored value, or null (unknown values are shown as
  /// stored, never guessed).
  static JournalMood? of(String? value) {
    final v = (value ?? '').trim().toLowerCase();
    for (final m in all) {
      if (m.value == v) return m;
    }
    return null;
  }
}

/// Stored mood as a small chip; nothing when there is no mood.
class MoodChip extends StatelessWidget {
  const MoodChip({super.key, required this.mood});

  final String? mood;

  @override
  Widget build(BuildContext context) {
    final raw = (mood ?? '').trim();
    if (raw.isEmpty) return const SizedBox.shrink();
    final known = JournalMood.of(raw);
    final colors = context.colorScheme;
    return StatusPill(
      label: known == null ? raw : '${known.emoji}  ${known.label}',
      foreground: colors.onSecondaryContainer,
      background: colors.secondaryContainer,
    );
  }
}

/// Entry photo: a local file being attached, or the stored URL.
class JournalPhoto extends StatelessWidget {
  const JournalPhoto({
    super.key,
    required this.source,
    this.height,
    this.width,
    this.radius = AppRadius.cardAll,
  });

  final String source;
  final double? height;
  final double? width;
  final BorderRadius radius;

  @override
  Widget build(BuildContext context) {
    final colors = context.colorScheme;
    final dpr = MediaQuery.devicePixelRatioOf(context);
    final cacheWidth =
        width == null || !width!.isFinite ? null : (width! * dpr).round();
    Widget fallback() => Container(
      height: height,
      width: width,
      color: colors.surfaceContainerHigh,
      alignment: Alignment.center,
      child: Icon(
        Icons.image_not_supported_outlined,
        color: colors.onSurfaceVariant,
      ),
    );

    final Widget image =
        source.startsWith('http')
            ? CachedNetworkImage(
              imageUrl: source,
              height: height,
              width: width,
              fit: BoxFit.cover,
              memCacheWidth: cacheWidth,
              placeholder:
                  (_, __) => Container(
                    height: height,
                    width: width,
                    color: colors.surfaceContainerHigh,
                  ),
              errorWidget: (_, __, ___) => fallback(),
            )
            : Image.file(
              File(source),
              height: height,
              width: width,
              fit: BoxFit.cover,
              cacheWidth: cacheWidth,
              errorBuilder: (_, __, ___) => fallback(),
            );
    return ClipRRect(borderRadius: radius, child: image);
  }
}

