/// `created_at` as local time (existing convention: parse, then
/// `toLocal()`), or null when invalid.
DateTime? journalTime(String? createdAt) =>
    DateTime.tryParse((createdAt ?? '').trim())?.toLocal();

String _fmt(String locale, String Function(String l) f, String Function() fb) {
  for (final l in [locale, 'en']) {
    try {
      return f(l);
    } catch (_) {
      // Locale data unavailable; try the next option.
    }
  }
  return fb();
}

String journalMonthLabel(DateTime t, String locale) => _fmt(
  locale,
  (l) => intl.DateFormat.yMMMM(l).format(t),
  () => '${t.year}-${t.month.toString().padLeft(2, '0')}',
);

String journalDateTimeLabel(DateTime t, String locale) => _fmt(
  locale,
  (l) =>
      '${intl.DateFormat.yMMMEd(l).format(t)} · ${intl.DateFormat.jm(l).format(t)}',
  () => t.toIso8601String(),
);

({String day, String weekday}) journalDayBadge(DateTime t, String locale) => (
  day: _fmt(locale, (l) => intl.DateFormat.d(l).format(t), () => '${t.day}'),
  weekday: _fmt(locale, (l) => intl.DateFormat.E(l).format(t), () => ''),
);
